"""Step 0: read-only audit of existing data -> data/inventory/00_existing_audit.md (run: python -I src/inventory/audit_existing.py)."""
import os, sys, glob
import pandas as pd, geopandas as gpd, pyogrio
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
L = []
def P(*a):
    s = " ".join(str(x) for x in a); L.append(s); print(s)

cnt = gpd.read_file("zip://data/raw_new/census_counties/cb_2024_us_county_500k.zip").to_crs(4326)
A_IDS = {"37183": "Wake", "37063": "Durham", "37135": "Orange"}
B_IDS = {"37129": "New Hanover", "37019": "Brunswick", "37141": "Pender"}
A = cnt[cnt.GEOID.isin(A_IDS)]; B = cnt[cnt.GEOID.isin(B_IDS)]
# 10 km / 40 km buffers in UTM 17N (EPSG:32617); NC spans ~ -84..-75 so fine for these areas
Au = A.to_crs(32617).geometry.union_all(); Bu = B.to_crs(32617).geometry.union_all()
Abuf = gpd.GeoSeries([Au.buffer(10_000)], crs=32617).to_crs(4326).iloc[0]
Bbuf = gpd.GeoSeries([Bu.buffer(40_000)], crs=32617).to_crs(4326).iloc[0]
Ageo = A.geometry.union_all(); Bgeo = B.geometry.union_all()

def count_in(gdf):
    """gdf in EPSG:4326 points"""
    g = gdf.geometry
    return dict(total=len(gdf), A_counties=int(g.within(Ageo).sum()), A_buf10=int(g.within(Abuf).sum()),
                B_counties=int(g.within(Bgeo).sum()), B_buf40=int(g.within(Bbuf).sum()))

P("# Step 0 - audit of existing data (read-only)\n")
P("Generated by `src/inventory/audit_existing.py`. Area A = Wake+Durham+Orange (+10 km), Area B = New Hanover+Brunswick+Pender (+40 km). Counties: Census cb_2024_us_county_500k.\n")
P("**Path corrections vs the brief:** `data/raw/lsr_*.xlsx` is actually `data/lsr_*.xlsx`; `data/raw/` is gitignored and holds nc.osm.pbf + osm_roads_{019,129,141}.parquet; no `osm_roads_*.parquet` for Area A exists. A statewide road parquet exists at `data/phase2/t10/osm_roads_nc.parquet`. `data/phase2/fema_nfhl.parquet` (Cape Fear NFHL, 14,145 polygons) EXISTS although handoff README says 04_flood_hazard is MISSING.\n")

# ---- NCDOT structures
P("## 1. NCDOT StructureLocationsPoint.gdb.zip")
z = "data/phase0/raw/NCDOTStructureLocationsPoint.gdb.zip"
P("- layers:", pyogrio.list_layers(z).tolist(), "| size", os.path.getsize(z), "bytes | vintage: 2026 Q1 (modified 2026-04-27, per docs/phase0_sources.md)")
info = pyogrio.read_info(z)
P("- CRS:", info["crs"], "| feature count:", info["features"], "| geometry:", info["geometry_type"])
s = gpd.read_file(z)
P("- fields:", list(s.columns))
bad = s[(s.geometry.is_empty) | (s.geometry.isna())]
P("- null/empty geometries:", len(bad))
s = s[~(s.geometry.is_empty | s.geometry.isna())].to_crs(4326)
ok = s[(s.geometry.x.between(-85, -75)) & (s.geometry.y.between(33, 37))]
P("- points outside NC bbox (bad coords):", len(s) - len(ok))
c = count_in(ok); P("- counts:", c)
cc = [x for x in s.columns if "COUNTY" in x.upper()]; P("- county-like cols:", cc)
if cc:
    P("- distinct counties (statewide?):", s[cc[0]].nunique())
    for col in cc[:1]:
        for nm in list(A_IDS.values()) + list(B_IDS.values()):
            P(f"  - {nm}: {int((s[col].astype(str).str.upper().str.contains(nm.upper())).sum())}")
P("- **Statewide: yes** (covers all NC counties). Covers Area A: yes. Area B: yes (already clipped to `ncdot_structures_pilot.parquet`).\n")
ncdot_pts = ok

# ---- NBI
P("## 2. NBI_NC25.txt")
n = pd.read_csv("data/phase0/raw/NBI_NC25.txt", quotechar="'", dtype=str, low_memory=False)
P("- rows:", len(n), "| cols:", n.shape[1], "| vintage: FHWA 2025 delimited (data as submitted 2025)")
cd = n["COUNTY_CODE_003"].str.strip().str.zfill(3)
P("- distinct county codes:", cd.nunique())
for fips, nm in {**A_IDS, **B_IDS}.items():
    P(f"  - {nm} ({fips}): {(cd == fips[2:]).sum()} bridges")
P("- years in YEAR_BUILT_027 min/max:", n["YEAR_BUILT_027"].astype(float).min(), n["YEAR_BUILT_027"].astype(float).max())
P("- **Statewide: yes.** Covers A and B. Lat/long are DDMMSSss / DDDMMSSss (needs conversion). No NBI file is geometry-ready; join to NCDOT by STRUCTURE_NUMBER_008.\n")

# ---- LSR
P("## 3. lsr_201809132029_201810212029.xlsx (Florence window only)")
for f in sorted(glob.glob("data/lsr_*.xlsx")):
    x = pd.read_excel(f)
    t = pd.to_datetime(x["Report Time (UTC Timezone)"])
    P(f"- {f}: {len(x)} rows, {t.min()} .. {t.max()} UTC; cols {list(x.columns)}")
    P("  - event types:", x["Event Type"].value_counts().head(12).to_dict())
    g = gpd.GeoDataFrame(x, geometry=gpd.points_from_xy(x.Lon, x.Lat), crs=4326)
    P("  - counts:", count_in(g))
    fl = g[g["Event Type"].astype(str).str.contains("FLASH FLOOD|FLOOD", case=False)]
    P("  - FLOOD/FLASH FLOOD subset:", count_in(fl) if len(fl) else 0)
P("- **Florence (Sep 13-Oct 21 2018) and Matthew (Oct 7-12 2016) windows only.** These are storm reports, not closures. Area A counts above show how thin.\n")

# ---- OSM
P("## 4. OSM files")
for f in ["data/raw/nc.osm.pbf", "data/phase2/t10/osm_roads_nc.parquet", "data/phase1b/raw/south-carolina-latest.osm.pbf"] + sorted(glob.glob("data/raw/osm_roads_*.parquet")) + ["data/phase0/osm_roads.parquet"]:
    P(f"- {f}: {os.path.getsize(f)/1e6:.1f} MB")
r = gpd.read_parquet("data/phase2/t10/osm_roads_nc.parquet")
P("- osm_roads_nc.parquet: rows", len(r), "| CRS", r.crs, "| cols", list(r.columns))
b = r.total_bounds; P("  - bounds", b.round(3).tolist())
rc = r.geometry.centroid
rcg = gpd.GeoSeries(rc, crs=r.crs).to_crs(4326)
P("  - segments with centroid in A+10km:", int(rcg.within(Abuf).sum()), "| in B+40km:", int(rcg.within(Bbuf).sum()))
P("- nc.osm.pbf: Geofabrik NC extract dated 2026-10-09 -> statewide, covers A and B. Read by src/k2_00a_osm_pbf.py.")
P("- osm_roads_{019,129,141}.parquet: per-county Area-B only. **Area A: neither**.\n")

# ---- Hospitals / handoff
P("## 5. Hospitals, fire stations, crossings, terrain")
h = pd.read_csv("data/phase1/raw/Hospital_General_Information.csv", dtype=str)
P("- CMS Hospital_General_Information.csv rows", len(h), "cols", list(h.columns))
nc = h[h["State"] == "NC"]; P("  - NC rows:", len(nc), "| ED=Yes:", int((nc["Emergency Services"] == "Yes").sum()))
cm = nc["County/Parish"].str.upper()
P("  - NC rows in Wake/Durham/Orange:", int(cm.isin(["WAKE", "DURHAM", "ORANGE"]).sum()), "| Cape Fear 3:", int(cm.isin(["NEW HANOVER", "BRUNSWICK", "PENDER"]).sum()))
P("  - **No lat/lon in CMS file** (geocoded by us for Area B only: hospitals_geocoded.csv).")
for f in ["handoff_for_shreyas/06_facilities/hospitals_40km.csv", "handoff_for_shreyas/06_facilities/fire_stations_40km.csv"]:
    d = pd.read_csv(f); P(f"- {f}: {len(d)} rows, cols {list(d.columns)}")
for f in ["handoff_for_shreyas/02_crossings/crossings_v2.parquet", "handoff_for_shreyas/03_terrain_proxy/tnm_1m_products.parquet", "handoff_for_shreyas/03_terrain_proxy/s4_sample.parquet", "data/phase2/fema_nfhl.parquet"]:
    try:
        d = gpd.read_parquet(f) if "nfhl" in f or "crossings" in f else pd.read_parquet(f)
    except Exception as e:
        d = pd.read_parquet(f)
    P(f"- {f}: {len(d)} rows, cols {list(d.columns)[:30]}")
    if "bbox" in str(d.columns) or hasattr(d, "total_bounds"):
        try: P("  - bounds", d.total_bounds.round(3).tolist())
        except Exception: pass
t = pd.read_parquet("handoff_for_shreyas/03_terrain_proxy/tnm_1m_products.parquet")
for c_ in t.columns:
    if "title" in c_.lower() or "project" in c_.lower() or "date" in c_.lower(): P(f"  - {c_} sample:", t[c_].astype(str).value_counts().head(5).to_dict())
P("\n(See bottom-line verdict in 00_existing_audit_verdict section appended by hand.)")
open("data/inventory/00_existing_audit.md", "w", encoding="utf-8").write("\n".join(L))
